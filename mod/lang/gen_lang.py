"""Generate RestoryVersus.Plugin/Lang.cs from translations.py, checked against the English keys in VersusMenu.cs.
Usage: python -I gen_lang.py   (from anywhere; paths are relative to this file)"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PLUGIN = os.path.join(HERE, "..", "RestoryVersus.Plugin")
LANGS = ["es", "fr", "de", "zh", "ja", "ko", "pt"]

ns = {}
exec(open(os.path.join(HERE, "translations.py"), encoding="utf-8").read(), ns)
T = ns["T"]

menu = open(os.path.join(PLUGIN, "VersusMenu.cs"), encoding="utf-8").read()
i = menu.index("private static readonly Dictionary<string, string[]> Strings")
block = menu[i:menu.index("};", i)]
english = dict(re.findall(r'\{ "([^"]+)", new\[\] \{ "((?:[^"\\]|\\.)*)", "(?:[^"\\]|\\.)*" \} \}', block))
# A key twice in Strings throws when VersusMenu's type loads, and the whole mod goes with it (seen once).
all_keys = re.findall(r'\{ "([^"]+)", new\[\] \{', block)
dupes = sorted({k for k in all_keys if all_keys.count(k) > 1})
if dupes:
    sys.exit("duplicate keys in VersusMenu.Strings: " + ", ".join(dupes))

problems = []
for key, en in english.items():
    want = sorted(re.findall(r"\{[a-z]+\}", en))
    for lang in LANGS:
        text = T.get(key, {}).get(lang)
        if text is None:
            problems.append(f"{key}: no {lang}")
            continue
        if sorted(re.findall(r"\{[a-z]+\}", text)) != want:
            problems.append(f"{key}/{lang}: placeholders {want} not kept")
for key in T:
    if key not in english:
        problems.append(f"{key}: not a menu key")
if problems:
    print("\n".join(problems))
    sys.exit(1)


def cs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = ["// Generated by mod/lang/gen_lang.py from mod/lang/translations.py: edit those, not this file.",
       "using System.Collections.Generic;", "", "namespace RestoryVersus", "{",
       "    // The menu in the game's other languages (English and Russian are in VersusMenu.Strings).",
       "    internal static class Lang", "    {",
       "        public static readonly Dictionary<string, Dictionary<string, string>> Table = new Dictionary<string, Dictionary<string, string>>",
       "        {"]
for lang in LANGS:
    out.append("            { " + cs(lang) + ", new Dictionary<string, string>")
    out.append("                {")
    for key in english:
        out.append("                    { " + cs(key) + ", " + cs(T[key][lang]) + " },")
    out.append("                }")
    out.append("            },")
out += ["        };", "    }", "}", ""]
open(os.path.join(PLUGIN, "Lang.cs"), "w", encoding="utf-8").write("\n".join(out))
print(f"Lang.cs: {len(english)} keys x {len(LANGS)} languages")
